# Estimate demand relationships and inspect fit diagnostics. Use the ML stage for future forecasts.
suppressPackageStartupMessages(library(jsonlite))
suppressPackageStartupMessages(library(mgcv))
if (.Platform$OS.type=='windows') try(Sys.setlocale('LC_CTYPE','English_United States.utf8'),silent=TRUE)
args <- commandArgs(trailingOnly=TRUE)
cfg <- fromJSON(args[1],simplifyVector=FALSE)
out <- args[2]
d <- read.csv(cfg$paths$demand_training,check.names=FALSE,fileEncoding='UTF-8-BOM')
positive_formula <- as.formula(cfg$demand$positive_formula)
zero_formula <- as.formula(cfg$demand$zero_formula)
needed <- union(all.vars(positive_formula),all.vars(zero_formula))
if (!all(needed %in% names(d))) stop(paste('Missing GAM fields:',paste(setdiff(needed,names(d)),collapse=', ')))
if (anyNA(d[,needed,drop=FALSE])) stop('GAM input contains missing values; no implicit row deletion is allowed')
if (!all(vapply(d[,needed,drop=FALSE],function(x) is.numeric(x)&&all(is.finite(x)),logical(1)))) stop('GAM fields must be finite numeric values')
if (any(d$zero_trip != as.numeric(d$Trips==0))) stop('zero_trip must equal 1 for zero Trips and 0 otherwise')
if (any(d$Trips<0)||!all(d$FixedRoute %in% c(0,1))||!all(d$DRTRoute==1-d$FixedRoute)) stop('Invalid demand response/service flags')
set.seed(cfg$seed)
res_model <- gam(positive_formula,family=tw(),data=d[d$Trips>0,,drop=FALSE],method='REML')
res_model_zero <- gam(zero_formula,family=binomial(),data=d,method='REML')
pzero <- as.numeric(predict(res_model_zero,d,type='response'))
positive <- as.numeric(predict(res_model,d,type='response'))
candidates <- unlist(cfg$demand$threshold_candidates)
errors <- sapply(candidates,function(x) abs(mean(d$zero_trip)-mean(pzero>x)))
threshold <- candidates[which.min(errors)]
fitted <- positive*as.numeric(pzero<=threshold)
result <- d[,c('Hour','GridID_O','GridID_D','FixedRoute','DRTRoute','Trips')]
result$PositiveFlow <- positive
result$ZeroProbability <- pzero
result$FittedTrips <- fitted
write.csv(result,file.path(out,'gam_fitted_values.csv'),row.names=FALSE)
saveRDS(list(positive=res_model,zero=res_model_zero,threshold=threshold,positive_formula=positive_formula,zero_formula=zero_formula),file.path(out,'hurdle_tweedie_models.rds'))
diagnostics <- list(training_rows=nrow(d),positive_rows=sum(d$Trips>0),zero_threshold=threshold,
 observed_total=sum(d$Trips),fitted_total=sum(fitted),in_sample_MAE=mean(abs(fitted-d$Trips)),
 in_sample_RMSE=sqrt(mean((fitted-d$Trips)^2)),positive_converged=res_model$converged,zero_converged=res_model_zero$converged,
 note='In-sample estimation diagnostics only. Future scenario demand is generated by the saved ML deployment bundle, not these fitted GAMs.')
if (!isTRUE(res_model$converged)||!isTRUE(res_model_zero$converged)) stop('A GAM did not converge')
write_json(diagnostics,file.path(out,'demand_diagnostics.json'),pretty=TRUE,auto_unbox=TRUE)
capture.output(summary(res_model),summary(res_model_zero),file=file.path(out,'demand_summary.txt'))
capture.output(sessionInfo(),file=file.path(out,'demand_sessionInfo.txt'))
pdf(file.path(out,'demand_model_diagnostics.pdf'))
gam.check(res_model)
gam.check(res_model_zero)
dev.off()
